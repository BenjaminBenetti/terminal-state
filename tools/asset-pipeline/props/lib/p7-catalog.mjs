// Shared writer of the iteration-07 runtime catalog game/src/gen/props07.catalog.ts (used by build-props-iteration07.mjs and
// build-meshy-t25.mjs so both generators always produce the same file).
//
// Rows come from the iteration-07 provenance outputs (game/public/assets/derivatives/props-iteration07.json). Since the Meshy
// T2.5 replacement (task studio-meshy-game-replacement-20261029-01) a kind whose model was replaced takes its runtime row from the
// T2.5 provenance (game/public/assets/derivatives/meshy-t25-props-20261029.json, records with a `p7Key`): url / bytes / triangles /
// colour atlas / GPU estimate / measured surfaces of the NEW file, mode 'T25'. The measured w / h / d stay the iteration-07 footprint
// (the T2.5 derivative is fitted to exactly that box), so P7_PROP_DEFS, layouts and colliders are unchanged.
import fs from 'node:fs';
import path from 'node:path';

export const T25_PROPS_PROVENANCE = 'game/public/assets/derivatives/meshy-t25-props-20261029.json';

/** p7 key -> T2.5 catalog override (empty when the T2.5 provenance does not exist yet). */
export function t25CatalogOverrides(repo) {
  const f = path.join(repo, T25_PROPS_PROVENANCE);
  if (!fs.existsSync(f)) return new Map();
  const doc = JSON.parse(fs.readFileSync(f, 'utf8'));
  return new Map((doc.records ?? []).filter(r => r.p7Key && r.catalog).map(r => [r.p7Key, r.catalog]));
}

const surfRow = s => `{y: ${s.y}, x0: ${s.x0}, x1: ${s.x1}, z0: ${s.z0}, z1: ${s.z1}, clear: ${s.clear}, area: ${s.areaM2 ?? s.area}}`;

/** The catalog TypeScript source. `outputs` = props-iteration07.json outputs; `overrides` = t25CatalogOverrides(). */
export function p7CatalogSource(outputs, overrides = new Map()) {
  const rows = outputs.slice().sort((a, b) => a.key.localeCompare(b.key)).map(o => {
    const t = overrides.get(o.key);
    if (t) return `  ${o.key}: {url: '${t.url}', bytes: ${t.bytes}, w: ${t.w}, h: ${t.h}, d: ${t.d}, tris: ${t.tris}, tex: ${t.tex}, gpuBytes: ${t.gpuBytes}, mode: 'T25', surfaces: [${(t.surfaces ?? []).map(surfRow).join(', ')}]},`;
    const m = o.dimensionsMeters.measured;
    const surf = (o.surfaces ?? []).map(surfRow).join(', ');
    return `  ${o.key}: {url: '${o.output.replace(/^game\/public\//, '')}', bytes: ${o.bytes}, w: ${m.w}, h: ${m.h}, d: ${m.d}, tris: ${o.triangles}, tex: ${o.textures.baseColor.size[0]}, gpuBytes: ${o.gpuTextureBytesEstimate}, mode: '${o.mode}', surfaces: [${surf}]},`;
  });
  return `// GENERATED by tools/asset-pipeline/props/build-props-iteration07.mjs from game/public/assets/derivatives/props-iteration07.json — do not edit.
// Iteration-07 runtime prop models (Lane P2): measured dims (metres, front +Z, origin bottom-centre), bytes, triangles, colour atlas
// size, GPU texture estimate, generation mode and measured support surfaces (output space). Prototype, unapproved, gameReady false.
// mode 'T25': replaced by the reference-conditioned Meshy T2.5 derivative (derivatives/meshy-t25-props-20261029.json; same footprint).
export interface P7Surface { y: number; x0: number; x1: number; z0: number; z1: number; clear: number; area: number }
export interface P7Model { url: string; bytes: number; w: number; h: number; d: number; tris: number; tex: number; gpuBytes: number; mode: 'SV' | 'MV' | 'T25'; surfaces: readonly P7Surface[] }
export const P7_MODELS = {
${rows.join('\n')}
} as const satisfies Record<string, P7Model>;
export type P7ModelKey = keyof typeof P7_MODELS;
`;
}
