// Iteration 11 (task studio-pistol-hit-audio-20261028-01): runtime derivative of the ONE authorized Sound Lab pistol shot.
// Reads reference/tasks/pistol-hit-audio-20261028/audio/raw/i11-pistol-shot-01.wav (verified against its sidecar SHA),
// writes game/public/assets/audio/i11-pistol-shot-01.mp3, game/src/audio/manifest.iteration11.generated.ts and
// game/public/assets/derivatives/audio-iteration11-pistol.json. Ops: onset trim (first event), cosine fades, mono,
// -1 dBFS peak, MP3. Edits the generated clip only; never creates sound.
// Usage: node tools/audio-pipeline/build-iteration11-pistol.mjs
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {Mp3Encoder} from '@breezystack/lamejs';
import {readWav, toInt16} from './lib/wav.mjs';
import * as D from './lib/dsp.mjs';

const ROOT = path.resolve(import.meta.dirname, '../..');
const AUDIO = path.join(ROOT, 'reference/tasks/pistol-hit-audio-20261028/audio');
const ID = 'i11-pistol-shot-01', CUE = 'pistolShot';
const OUT = path.join(ROOT, 'game/public/assets/audio', `${ID}.mp3`);
const MANIFEST_TS = path.join(ROOT, 'game/src/audio/manifest.iteration11.generated.ts');
const PROV = path.join(ROOT, 'game/public/assets/derivatives/audio-iteration11-pistol.json');
const R = {maxS: 1.4, tailDb: -45, holdMs: 60, fadeIn: 0.002, fadeOut: 0.12, kbps: 128};
const sha256 = b => createHash('sha256').update(b).digest('hex');
const LAME = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules/@breezystack/lamejs/package.json'), 'utf8')).version;

const clip = JSON.parse(fs.readFileSync(path.join(AUDIO, 'queue.json'), 'utf8')).clips.find(c => c.id === ID);
const term = JSON.parse(fs.readFileSync(path.join(AUDIO, 'ledger', ID, 'terminal.json'), 'utf8'));
if (term.state !== 'done') throw new Error('job not done');
const wavBytes = fs.readFileSync(path.join(AUDIO, 'raw', `${ID}.wav`));
const side = JSON.parse(fs.readFileSync(path.join(AUDIO, 'raw', `${ID}.sidecar.json`), 'utf8'));
const rawSha = sha256(wavBytes);
if (rawSha !== side.rawSha256 || rawSha !== term.rawSha256) throw new Error('raw bytes changed (sha mismatch) — refusing');
const w = readWav(wavBytes), sr = w.sampleRate;
const metrics = D.analyse(w.channels, sr);
const mono = D.downmix(w.channels);
const on = D.onsets(mono, sr, {riseDb: 6, floorDb: -30, minGapS: 0.05});
const a = Math.max(0, (on.length ? on[0] : 0) - Math.round(0.004 * sr));
const b = D.eventEnd(mono, sr, a, {maxS: R.maxS, tailDb: R.tailDb, split: false, holdMs: R.holdMs});
const chs = D.slice([mono], a, b);
const outS = Math.min(R.fadeOut, (b - a) / sr * 0.4);
D.fade(chs, sr, R.fadeIn, outS);
const gain = D.normalisePeak(chs, -1);
const enc = new Mp3Encoder(1, sr, R.kbps), ints = toInt16(chs[0]), parts = [];
for (let i = 0; i < ints.length; i += 1152) { const o = enc.encodeBuffer(ints.subarray(i, i + 1152)); if (o.length) parts.push(Buffer.from(o)); }
const tail = enc.flush(); if (tail.length) parts.push(Buffer.from(tail));
const mp3 = Buffer.concat(parts);
const durS = +(chs[0].length / sr).toFixed(4);
fs.writeFileSync(OUT, mp3);
fs.writeFileSync(MANIFEST_TS, `// GENERATED by tools/audio-pipeline/build-iteration11-pistol.mjs from the Sound Lab raw — do not edit by hand.
// Provenance: public/assets/derivatives/audio-iteration11-pistol.json.

import type {ClipRef} from './manifest.generated';

export const CLIP_MANIFEST_I11: Readonly<Record<string, readonly ClipRef[]>> = {
 ${CUE}: [
  ${JSON.stringify({url: `assets/audio/${ID}.mp3`, dur: durS, src: ID})},
 ],
};

/** Cues this build should have produced but could not (none). */
export const CLIP_GAPS_I11: readonly string[] = [];
/** Total bytes of this build's derivatives. */
export const CLIP_BYTES_I11 = ${mp3.length};
`);
const prov = {task: 'studio-pistol-hit-audio-20261028-01', generatedBy: 'tools/audio-pipeline/build-iteration11-pistol.mjs',
  policy: 'Sound Lab only: derivative of ONE freshly authorized Sound Lab job (no synthesis/stock/hosted audio); replaces the pitched rifle-shot fallback for the pistol.',
  license: {status: 'Conditional prototype: Stability AI Community License + Gemma terms; not production/commercial clearance. Unreviewed by ear on the worker.', gameReady: false},
  derivatives: [{file: `game/public/assets/audio/${ID}.mp3`, url: `assets/audio/${ID}.mp3`, bytes: mp3.length, sha256: sha256(mp3), cue: CUE, durationS: durS, channels: 1, sampleRate: sr, codec: 'mp3', kbps: R.kbps,
    source: {clip: ID, rawFile: `reference/tasks/pistol-hit-audio-20261028/audio/raw/${ID}.wav`, rawSha256: rawSha, labFile: side.labFile ?? term.labFile, jobId: term.jobId,
      prompt: clip.prompt, negativePrompt: clip.negative_prompt, seed: clip.seed, steps: clip.steps, cfg: clip.cfg, seconds: clip.seconds, profile: side.model?.profile ?? null, modelRevision: side.model?.revision ?? null},
    rawMetrics: metrics,
    ops: [{op: 'downmix', to: 'mono'}, {op: 'trim', startS: +(a / sr).toFixed(4), endS: +(b / sr).toFixed(4), mode: 'first event'}, {op: 'fade', inS: R.fadeIn, outS: +outS.toFixed(4), curve: 'cosine'},
      {op: 'normalise', peakDbfs: -1, gainDb: +gain.toFixed(2)}, {op: 'encode', codec: 'mp3', encoder: `@breezystack/lamejs ${LAME} (LGPL-3.0, build-time only)`, kbps: R.kbps}]}]};
fs.writeFileSync(PROV, JSON.stringify(prov, null, 1) + '\n');
console.log(`${ID}: ${durS}s, ${mp3.length} B, sha ${sha256(mp3).slice(0, 12)}, trim ${(a / sr).toFixed(3)}-${(b / sr).toFixed(3)}s, peak gain ${gain.toFixed(2)} dB, raw peak ${metrics.peakDb} flat ${metrics.flatDb}`);
